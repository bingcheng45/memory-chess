#!/usr/bin/env node
/**
 * Regenerate src/lib/leaderboard/countryCodes.ts.
 *
 * ECMA-402 offers no way to enumerate ICU's regions -- `Intl.supportedValuesOf`
 * has no "region" key, it throws -- so brute-forcing every two-letter pair
 * through Intl.DisplayNames is the only way to recover the set.
 *
 * ICU names more than ISO 3166-1 assigns, which is what the three exclusion
 * lists below are for. ICU's tables also differ between Node versions and
 * between browsers, so the result is committed rather than recomputed at
 * runtime.
 *
 * Usage: node scripts/generate-country-codes.mjs
 */
import { writeFileSync } from "node:fs";

/** Formerly assigned, since removed from ISO 3166-1. ICU still names them. */
const WITHDRAWN = [
  "AN", "BU", "CS", "DD", "DY", "FX", "HV",
  "NH", "RH", "SU", "TP", "VD", "YD", "YU", "ZR",
];

/**
 * Exceptionally reserved codes and CLDR aggregates: ICU names them, but none
 * denotes a country ISO 3166-1 assigns. UK belongs here rather than above, as
 * it is live today and reserved for the United Kingdom alongside GB.
 */
const NOT_A_COUNTRY = [
  "AC", "CP", "CQ", "DG", "EA", "EU",
  "EZ", "IC", "QO", "TA", "UK", "UN",
];

/**
 * The ranges ISO leaves to private use. XK is Kosovo, XA and XB are ICU's own
 * pseudo-locales, and ZZ is dropped here and re-enters deliberately as
 * WORLD_CODE in src/lib/leaderboard/countries.ts.
 */
const USER_ASSIGNED = ["XA", "XB", "XK", "ZZ"];

const LETTERS = [..."ABCDEFGHIJKLMNOPQRSTUVWXYZ"];

/** Measured against ICU in Node 26.8.1. A mismatch means ISO moved or this script broke. */
const ISO_3166_ALPHA2_COUNT = 249;
const OUTPUT_URL = new URL("../src/lib/leaderboard/countryCodes.ts", import.meta.url);

const displayNames = new Intl.DisplayNames(["en"], { type: "region" });
const excluded = new Set([...WITHDRAWN, ...NOT_A_COUNTRY, ...USER_ASSIGNED]);

// This filter rides on Intl.DisplayNames defaulting to fallback: "code". Switch
// that to "none" and `.of` returns undefined for unknown pairs, making the
// comparison universally true and collecting all 676.
const codes = LETTERS.flatMap((first) => LETTERS.map((second) => first + second))
  .filter((code) => displayNames.of(code) !== code)
  .filter((code) => !excluded.has(code))
  .sort();

if (codes.length !== ISO_3166_ALPHA2_COUNT) {
  console.error(
    `Expected ${ISO_3166_ALPHA2_COUNT} codes, got ${codes.length}.\n` +
      `This runtime's ICU data disagrees with the exclusion lists in this script. ` +
      `Reconcile them against ISO 3166-1 before regenerating; do not relax the count.`,
  );
  process.exit(1);
}

const file = `// Generated by scripts/generate-country-codes.mjs. Do not hand-edit.

export const ISO_3166_ALPHA2 = [
${codes.map((code) => `  "${code}",`).join("\n")}
] as const;
`;

writeFileSync(OUTPUT_URL, file);

console.log(`${codes.length} ISO 3166-1 alpha-2 codes written to src/lib/leaderboard/countryCodes.ts`);
