#!/usr/bin/env node
/**
 * Regenerate src/lib/home/showcaseReplay.ts from the Linares 1998 game record,
 * read through chess.js: what each piece of the hero's study position attacks and
 * where it may legally go, and one frame per ply from there to the end of the game.
 *
 * The tables are committed so chess.js stays out of the client bundle. The
 * position comes from replaying the game record, never from the showcase data,
 * so the showcase test can hold the two against each other.
 *
 * Usage: node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON scripts/generate-showcase-reach.mjs [--check]
 * --check writes nothing and exits 1 when the committed table is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { Chess } from "chess.js";

const fromRoot = (path) => join(process.cwd(), path);
const OUTPUT = "src/lib/home/showcaseReplay.ts";
const { LINARES_MOVES, STUDY_PLY } = await import(pathToFileURL(fromRoot("src/lib/home/showcaseGame.ts")).href);

const FILES = [..."abcdefgh"];
const SQUARES = FILES.flatMap((file) => [1, 2, 3, 4, 5, 6, 7, 8].map((rank) => `${file}${rank}`));

const game = new Chess();
LINARES_MOVES.slice(0, STUDY_PLY).forEach((move) => game.move(move));
const fen = game.fen();

/** The same position with the other side to move, so either colour's legal moves can be listed. */
function withTurn(color) {
  if (game.turn() === color) return new Chess(fen);
  const fields = fen.split(" ");
  fields[1] = color;
  fields[3] = "-";
  return new Chess(fields.join(" "));
}

function reachOf(square, color) {
  const attacks = SQUARES.filter((target) => target !== square && game.attackers(target, color).includes(square)).sort();
  const legal = withTurn(color)
    .moves({ square, verbose: true })
    .map((move) => ({ to: move.to, san: move.san }));
  return { attacks, legal };
}

const strings = (values) => `[${values.map((value) => `"${value}"`).join(", ")}]`;

/** Each ply after the study position: the move, the square of any capture, and the board it leaves. */
function frames() {
  const replay = new Chess(fen);
  return LINARES_MOVES.slice(STUDY_PLY).map((san) => {
    const move = replay.move(san);
    const captured = move.captured ? (move.isEnPassant() ? `${move.to[0]}${move.from[1]}` : move.to) : null;
    return { san: move.san, from: move.from, to: move.to, captured, fen: replay.fen() };
  });
}

function render() {
  const pieces = game.board().flat().filter(Boolean);
  const entries = pieces.map(({ square, color }) => {
    const { attacks, legal } = reachOf(square, color);
    const moves = legal.map((move) => `      { to: "${move.to}", san: "${move.san}" },`);
    return [
      `  ${square}: {`,
      `    attacks: ${strings(attacks)},`,
      ...(moves.length ? ["    legal: [", ...moves, "    ],"] : ["    legal: [],"]),
      "  },",
    ].join("\n");
  });
  const plies = frames().map(
    ({ san, from, to, captured, fen: after }) =>
      `  { san: "${san}", from: "${from}", to: "${to}", captured: ${captured ? `"${captured}"` : "null"}, fen: "${after}" },`,
  );
  return [
    "// Generated by scripts/generate-showcase-reach.mjs from the Linares 1998 game record. Do not edit.",
    'import type { ShowcaseFrame, ShowcaseReach } from "./showcase";',
    "",
    "export const SHOWCASE_REACH: ShowcaseReach = {",
    ...entries,
    "};",
    "",
    "export const SHOWCASE_FRAMES: readonly ShowcaseFrame[] = [",
    ...plies,
    "];",
    "",
  ].join("\n");
}

const next = render();
if (process.argv.includes("--check")) {
  if (readFileSync(fromRoot(OUTPUT), "utf8") !== next) {
    console.error(`${OUTPUT} is stale. Run: npm run generate:showcase`);
    process.exit(1);
  }
} else {
  writeFileSync(fromRoot(OUTPUT), next);
}
