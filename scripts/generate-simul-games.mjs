#!/usr/bin/env node
/**
 * Regenerate src/lib/home/intro/simulGames.ts: the games the 45-board intro plays.
 * The centre board replays the Opera Game. Each of the other boards plays one of
 * the opening lines, a seeded number of bot moves to reach the middlegame it shows
 * first, then the bot moves it plays during the intro.
 *
 * The bot is one-ply greedy with seeded noise: take material, give check, promote.
 * It only has to play legal, lively chess, not good chess. The games are committed
 * so chess.js stays out of the client bundle.
 *
 * Usage: node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON scripts/generate-simul-games.mjs [--check]
 * --check writes nothing and exits 1 when the committed games are stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { Chess } from "chess.js";

const fromRoot = (path) => join(process.cwd(), path);
const OUTPUT = "src/lib/home/intro/simulGames.ts";
const { OPERA_MOVES, OPENINGS, BOT_BOARDS, BOT_PLIES, SEED } = await import(
  pathToFileURL(fromRoot("src/lib/home/intro/simulSource.ts")).href
);

/** Most bot moves a board plays before the intro starts, so the boards open at different moments. */
const MAX_PRE_ROLL = 24;
const VALUE = { p: 1, n: 3, b: 3, r: 5, q: 9, k: 0 };

/** mulberry32: small, seedable, the same on every machine. */
function random(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function botMove(game, next) {
  let best = null;
  let bestScore = -Infinity;
  for (const move of game.moves({ verbose: true })) {
    const score =
      (move.captured ? VALUE[move.captured] * 1.2 : 0) +
      (move.san.includes("+") ? 0.6 : 0) +
      (move.promotion ? 8 : 0) -
      (move.piece === "k" ? 0.4 : 0) +
      next() * 1.1;
    if (score > bestScore) {
      bestScore = score;
      best = move;
    }
  }
  return best.san;
}

function placement(game) {
  const squares = new Map();
  for (const piece of game.board().flat()) {
    if (piece) squares.set(piece.square, piece.color === "w" ? piece.type.toUpperCase() : piece.type);
  }
  return squares;
}

function play(game, sans) {
  return sans.map((san) => {
    const before = placement(game);
    game.move(san);
    const after = placement(game);
    const squares = [...new Set([...before.keys(), ...after.keys()])].sort();
    const changes = squares
      .filter((square) => before.get(square) !== after.get(square))
      .map((square) => [square, after.get(square) ?? null]);
    return { san, changes };
  });
}

function operaBoard() {
  const game = new Chess();
  return { name: "Opera Game", fen: game.fen(), plies: play(game, OPERA_MOVES) };
}

function botBoard(index, next) {
  const opening = OPENINGS[index % OPENINGS.length];
  const game = new Chess();
  opening.moves.split(" ").forEach((san) => game.move(san));
  const preRoll = Math.floor(next() * MAX_PRE_ROLL);
  for (let ply = 0; ply < preRoll; ply++) game.move(botMove(game, next));
  const fen = game.fen();
  const sans = [];
  const ahead = new Chess(fen);
  for (let ply = 0; ply < BOT_PLIES; ply++) {
    if (ahead.isGameOver()) throw new Error(`Board ${index} (${opening.name}) ended after ${ply} plies. Change SEED.`);
    const san = botMove(ahead, next);
    ahead.move(san);
    sans.push(san);
  }
  return { name: opening.name, fen, plies: play(new Chess(fen), sans) };
}

function renderBoard({ name, fen, plies }) {
  const lines = plies.map(({ san, changes }) => {
    const list = changes.map(([square, piece]) => `["${square}", ${piece ? `"${piece}"` : "null"}]`).join(", ");
    return `      { san: "${san}", changes: [${list}] },`;
  });
  return [`  {`, `    name: "${name}",`, `    fen: "${fen}",`, `    plies: [`, ...lines, `    ],`, `  },`].join("\n");
}

function render() {
  const next = random(SEED);
  const boards = Array.from({ length: BOT_BOARDS }, (_, index) => botBoard(index, next));
  return [
    "// Generated by scripts/generate-simul-games.mjs from src/lib/home/intro/simulSource.ts. Do not edit.",
    'import type { SimulBoard } from "./simul";',
    "",
    `export const SIMUL_HERO: SimulBoard = ${renderBoard(operaBoard()).replace(/^  /gm, "").replace(/,$/, ";")}`,
    "",
    "export const SIMUL_BOARDS: readonly SimulBoard[] = [",
    ...boards.map(renderBoard),
    "];",
    "",
  ].join("\n");
}

const next = render();
if (process.argv.includes("--check")) {
  if (readFileSync(fromRoot(OUTPUT), "utf8") !== next) {
    console.error(`${OUTPUT} is stale. Run: npm run generate:simul`);
    process.exit(1);
  }
} else {
  writeFileSync(fromRoot(OUTPUT), next);
}
